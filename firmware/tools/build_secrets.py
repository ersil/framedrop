# PlatformIO pre-script for the photoframe environment. Reads two secrets from
# the environment and fails the build if either is missing or unusable:
#   PHOTOFRAME_WEB_PASSWORD   web UI and OTA password; only its SHA-256 is
#                             compiled in
#   PHOTOFRAME_SETUP_PASSWORD WPA2 password of the PhotoFrame-Setup network
#                             that appears when no home Wi-Fi is saved
# and three optional ones:
#   PHOTOFRAME_WIFI_SSID      home Wi-Fi the device joins when none is saved
#   PHOTOFRAME_WIFI_PASSWORD  its password (empty for an open network)
#   PHOTOFRAME_TZ             POSIX TZ string for file timestamps, default UTC0
#
# The values go into a generated header that every source file force-includes,
# not onto the compiler command line. On the command line SCons expands `$`
# and the shell runs backticks, which silently corrupted passwords, and
# `pio run -v` printed the setup password on every compile line.
import hashlib
import os
import secrets

from SCons.Script import COMMAND_LINE_TARGETS

Import("env")  # noqa: F821  (provided by PlatformIO)

# Targets that compile nothing do not need the secrets. `pio run -t clean`
# runs SCons in clean mode rather than naming a target.
NO_COMPILE = {"clean", "cleanall", "fullclean", "buildfs", "uploadfs", "erase", "menuconfig"}
if env.GetOption("clean") or (
    COMMAND_LINE_TARGETS and set(COMMAND_LINE_TARGETS) <= NO_COMPILE
):
    Return()  # noqa: F821  (SCons builtin)


def fail(message):
    raise SystemExit("build_secrets.py: " + message)


def require(name):
    value = os.environ.get(name, "")
    if not value:
        fail("%s is not set in the environment" % name)
    return value


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


web = require("PHOTOFRAME_WEB_PASSWORD")
# A trailing newline from a copy-paste into a secret store would be hashed with the
# password, and nobody can type it into a browser.
if web != web.strip():
    fail("PHOTOFRAME_WEB_PASSWORD has leading or trailing whitespace")
setup = require("PHOTOFRAME_SETUP_PASSWORD")
# WPA2 accepts 8 to 63 printable ASCII characters; anything else makes
# WiFi.softAP() fail at runtime, which leaves a board with no console that
# cannot be provisioned.
if not (8 <= len(setup) <= 63) or any(not (0x20 <= ord(c) <= 0x7E) for c in setup):
    fail("PHOTOFRAME_SETUP_PASSWORD must be 8 to 63 printable ASCII characters")

wifi_ssid = os.environ.get("PHOTOFRAME_WIFI_SSID", "")
wifi_pass = os.environ.get("PHOTOFRAME_WIFI_PASSWORD", "")
if wifi_pass and not wifi_ssid:
    fail("PHOTOFRAME_WIFI_PASSWORD is set but PHOTOFRAME_WIFI_SSID is not")
if len(wifi_ssid.encode()) > 32:
    fail("PHOTOFRAME_WIFI_SSID is longer than 32 bytes")
if wifi_pass and not (8 <= len(wifi_pass.encode()) <= 63):
    fail("PHOTOFRAME_WIFI_PASSWORD must be 8 to 63 characters, or empty for an open network")
tz = os.environ.get("PHOTOFRAME_TZ", "") or "UTC0"
if any(not (0x20 < ord(c) <= 0x7E) for c in tz):
    fail("PHOTOFRAME_TZ must be a POSIX TZ string such as PST8PDT,M3.2.0,M11.1.0")

header = os.path.join(env.subst("$BUILD_DIR"), "photoframe_secrets.h")
os.makedirs(os.path.dirname(header), exist_ok=True)
content = (
    "// Generated by tools/build_secrets.py. Do not commit.\n"
    "#pragma once\n"
    "#define PRINTDROP_AUTH_PASS_HASH %s\n"
    "#define AP_PASSWORD %s\n"
    "#define HOME_WIFI_SSID %s\n"
    "#define HOME_WIFI_PASSWORD %s\n"
    "#define PHOTOFRAME_TZ %s\n"
    % (
        c_string(hashlib.sha256(web.encode()).hexdigest()),
        c_string(setup),
        c_string(wifi_ssid),
        c_string(wifi_pass),
        c_string(tz),
    )
)
# Rewrite only on change, so an unchanged password does not rebuild everything.
try:
    with open(header) as f:
        unchanged = f.read() == content
except OSError:
    unchanged = False

# SCons does not scan a header passed with -include, so a changed password
# would leave every object file as it was and the firmware would keep the old
# one. A random revision on the command line, renewed whenever the header
# changes, makes SCons recompile everything. It is random rather than derived
# from the secrets, so the build log reveals nothing about them.
rev_file = header + ".rev"
try:
    with open(rev_file) as f:
        rev = f.read().strip()
except OSError:
    rev = ""
if not unchanged or not rev:
    # The new revision is written before the header: if the build stops in
    # between, the next run still sees a changed header and renews it again.
    rev = secrets.token_hex(8)
    with open(rev_file, "w") as f:
        f.write(rev)
    with open(header, "w") as f:
        f.write(content)
    os.chmod(header, 0o600)

env.Append(CCFLAGS=["-include", header])
env.Append(CPPDEFINES=[("PHOTOFRAME_SECRETS_REV", "0x" + rev)])
